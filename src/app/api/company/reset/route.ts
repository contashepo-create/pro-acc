import { NextRequest } from 'next/server';
import { error } from '@/lib/api-helpers';

/**
 * /api/company/reset — ميزة تصفير قاعدة بيانات الشركة (أُلغيت نهائياً).
 *
 * قرار تشغيلي صريح من مالك المنصة: لا يجوز لأي عميل — حالي أو منتهي
 * الاشتراك أو معلّق أو جديد — أن يصفّر قاعدة بياناته بنفسه تحت أي ظرف.
 *
 * ما تم تنفيذه لضمان ذلك:
 *  1. هذا المسار أصبح "قبراً" (tombstone): يرفض كل الأفعال برمز 410 Gone
 *     ولا يستدعي أي RPC.
 *  2. ميجريشن 088 يحذف من قاعدة البيانات نفسها دوال التصفير
 *     (reset_company_business_data + دوال جلسات تيليجرام المرتبطة بها)،
 *     فلا يبقى أي مسار خلفي حتى لو استُدعيت الدوال مباشرة.
 *  3. بوابة تيليجرام لا تصدر رموز تأكيد للتصفير بعد الآن.
 *
 * إن أراد العميل البدء من جديد فعليه التواصل مع الدعم، وإن أراد بياناته
 * فهي متاحة له كجداول Excel/CSV عبر صفحة تحميل البيانات فقط.
 */

const GONE_MESSAGE =
  'ميزة تصفير قاعدة البيانات أُلغيت نهائياً ولا يمكن لأي عميل تصفير بياناته. ' +
  'للحصول على بياناتك استخدم صفحة تحميل البيانات (Excel/CSV)، وللبدء من جديد تواصل مع الدعم.';

export async function POST(_request: NextRequest) {
  return error(GONE_MESSAGE, 410);
}

export async function DELETE(_request: NextRequest) {
  return error(GONE_MESSAGE, 410);
}
