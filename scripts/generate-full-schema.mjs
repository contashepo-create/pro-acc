/**
 * Regenerate supabase-full-schema.sql from the canonical migration chain
 * (src/migrations/*.sql, the same chain `npm run migrate` applies).
 *
 * The previous checked-in copy was an outdated hand-written snapshot that
 * contained the WEAK bootstrap version of create_journal_entry (no balance
 * guard, no tenant checks). This generator removes that drift risk
 * permanently: the full-schema file is always an exact concatenation of the
 * real migrations, in order.
 *
 * Run:  node scripts/generate-full-schema.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const migrationsDir = path.resolve('src/migrations');
const outFile = path.resolve('supabase-full-schema.sql');

// Bootstrap migration 000 records the historical 001–006 files itself
// (they are already reflected inside 000's SQL). Including them again in a
// single concatenated snapshot would re-run duplicate CREATE TABLE
// statements; the incremental runner skips them the same way.
const SKIP_AFTER_BOOTSTRAP = new Set([
  '001-schema.sql',
  '002-notifications.sql',
  '003-subscriptions.sql',
  '004-admin-sessions.sql',
  '005-auth-extras.sql',
  '006-features.sql',
]);

const files = fs.readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql') && !SKIP_AFTER_BOOTSTRAP.has(f))
  .sort();
const header = `-- ============================================================================
-- Pro Acc — FULL SCHEMA (generated)
--
-- This file is AUTO-GENERATED from the canonical migration chain
-- (src/migrations/*.sql, applied in filename order) by:
--     node scripts/generate-full-schema.mjs
--
-- DO NOT EDIT THIS FILE BY HAND. Apply new changes as a new numbered file
-- under src/migrations/ and regenerate. Running "npm run migrate" is the
-- preferred way to apply the schema; this single-file snapshot exists for
-- manual bootstrapping in the Supabase SQL editor.
--
-- Chain included at generation time:
-- ${files.map((f) => `--   ${f}`).join('\n')}
-- ============================================================================

`;

const parts = [header];
for (const filename of files) {
  const sql = fs.readFileSync(path.join(migrationsDir, filename), 'utf8').trim();
  parts.push(`-- ----------------------------------------------------------------------------\n-- BEGIN ${filename}\n-- ----------------------------------------------------------------------------\n\n${sql}\n`);
}

fs.writeFileSync(outFile, parts.join('\n') + '\n');
console.log(`wrote ${outFile} from ${files.length} migrations`);
